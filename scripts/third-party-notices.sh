#!/bin/sh
# Prints the licence notices of the Go standard library and of every module
# compiled into the ahasend binary on the platforms releases are built for.
# It reads them from GOROOT and the module cache, using only the Go
# toolchain. `make notices` writes them to THIRD_PARTY_NOTICES.
set -eu

separator='================================================================================'

# print_notices NAME DIR prints the licence files at the top of DIR
print_notices() {
	found=
	for file in "$2"/*; do
		[ -f "$file" ] || continue
		case "$(basename "$file" | tr '[:lower:]' '[:upper:]')" in
		LICENSE* | LICENCE* | COPYING* | NOTICE* | PATENTS* | AUTHORS*)
			found=yes
			printf '%s\n%s: %s\n%s\n\n' "$separator" "$1" "$(basename "$file")" "$separator"
			cat "$file"
			printf '\n'
			;;
		esac
	done
	if [ -z "$found" ]; then
		echo "no licence file found for $1 in $2" >&2
		exit 1
	fi
}

modules=$(
	for os in linux darwin windows; do
		CGO_ENABLED=0 GOOS=$os go list -deps \
			-f '{{with .Module}}{{if not .Main}}{{.Path}}@{{.Version}} {{.Dir}}{{end}}{{end}}' . || exit 1
	done
)
modules=$(echo "$modules" | sort -u)

cat <<'EOF'
Third-party software notices for the AhaSend CLI

The ahasend binary includes the Go standard library and the modules listed
below. Their licence notices follow, as their licences require.

Generated by `make notices` from go.mod; do not edit.

EOF

goroot=$(go env GOROOT)
if [ ! -f "$goroot/LICENSE" ]; then
	echo "no licence file found for the Go standard library in $goroot: run the script with an official Go release, as make notices does" >&2
	exit 1
fi
print_notices "Go standard library" "$goroot"
echo "$modules" | while read -r module dir; do
	print_notices "$module" "$dir"
done
